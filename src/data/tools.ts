export const TOOLS_BY_ID: Record<string, Tool> = Object.fromEntries(TOOLS.map((t) => [t.id, t]));

export function getTool(id: string): Tool | undefined {
  return TOOLS_BY_ID[id];
}

export function getToolsByPillar(pillar: string): Tool[] {
  if (pillar === "all") return TOOLS;
  return TOOLS.filter((t) => t.pillar === pillar);
}

export function searchTools(query: string): Tool[] {
  const q = query.toLowerCase().trim();
  if (!q) return TOOLS;
  return TOOLS.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.tagline.toLowerCase().includes(q) ||
      t.id.includes(q),
  );
}

